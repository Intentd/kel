package gendoc

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// Registry describes the Go file Render writes.
type Registry struct {
	Package   string // package of the generated file
	Generator string // named in the "Code generated by" line
	Qualifier string // prefix for FunctionInfo and DomainInfo: "" inside package kel, "kel." outside
	Import    string // import path of package kel, when Qualifier is set
	Functions string // name of the functions variable
	Domains   string // name of the domains variable
}

// Render returns the gofmt'd Go source declaring fns and domains as
// kel.FunctionInfo and kel.DomainInfo slices.
func Render(r Registry, fns []Function, domains []Domain) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s. DO NOT EDIT.\n\npackage %s\n\n", r.Generator, r.Package)
	if r.Qualifier != "" {
		fmt.Fprintf(&b, "import %q\n\n", r.Import)
	}
	fmt.Fprintf(&b, "// %s is every domain, from the builders' doc comments.\n", r.Domains)
	fmt.Fprintf(&b, "var %s = []%sDomainInfo{\n", r.Domains, r.Qualifier)
	for _, d := range domains {
		fmt.Fprintf(&b, "\t{Name: %q, Title: %q, Intro: %s},\n", d.Name, d.Title, strconv.Quote(d.Intro))
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// %s is every function, from its doc comment.\n", r.Functions)
	fmt.Fprintf(&b, "var %s = []%sFunctionInfo{\n", r.Functions, r.Qualifier)
	for _, f := range fns {
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tName: %q,\n\t\tDomain: %q,\n", f.Name, f.Domain)
		fmt.Fprintf(&b, "\t\tDescription: %s,\n", strconv.Quote(f.Description))
		fmt.Fprintf(&b, "\t\tExample: %s,\n", strconv.Quote(f.Example))
		if len(f.SeeAlso) > 0 {
			fmt.Fprintf(&b, "\t\tSeeAlso: %s,\n", stringSlice(f.SeeAlso))
		}
		fmt.Fprintf(&b, "\t\tKeywords: %s,\n", stringSlice(f.Keywords))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func stringSlice(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
